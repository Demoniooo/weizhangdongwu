/**
 * 由锚点 {cueId: 真实秒} 构造 warp：真实秒 → 默认秒（分段线性，两端斜率 1 外推）。
 * 锚点为空时是恒等映射。
 */
export function makeWarp(anchors = {}) {
  const pts = Object.entries(anchors)
    .filter(([id]) => CUES[id] !== undefined)
    .map(([id, real]) => [real, CUES[id]])
    .sort((a, b) => a[0] - b[0]);
  if (pts.length === 0) return { toDefault: (t) => t, toReal: (T) => T, duration: DURATION };
  const map = (x, from, to) => {
    if (x <= pts[0][from]) return pts[0][to] + (x - pts[0][from]);
    for (let i = 1; i < pts.length; i++) {
      const a = pts[i - 1], b = pts[i];
      if (x <= b[from]) return a[to] + ((x - a[from]) / (b[from] - a[from] || 1)) * (b[to] - a[to]);
    }
    const z = pts[pts.length - 1];
    return z[to] + (x - z[from]);
  };
  const toDefault = (t) => map(t, 0, 1);
  const toReal = (T) => map(T, 1, 0);
  return { toDefault, toReal, duration: toReal(DURATION) };
}
